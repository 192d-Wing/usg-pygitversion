        f.branch_to("release/1.3.0")
        f.assert_full_semver("1.3.0-beta.1+1", c)
        f.make_a_commit()
        f.assert_full_semver("1.3.0-beta.1+2", c)
        f.checkout("develop")
        f.assert_full_semver("1.4.0-alpha.0", c)
        f.merge_no_ff("release/1.3.0")
        f.assert_full_semver("1.4.0-alpha.2", c)
        f.checkout("main")
        f.merge_no_ff("release/1.3.0")
        f.delete_branch("release/1.3.0")
        f.apply_tag("1.3.0")
        f.assert_full_semver("1.3.0", c)
        f.make_a_commit()
        f.assert_full_semver("1.3.1-1", c)
        f.apply_tag("1.3.1")
        f.assert_full_semver("1.3.1", c)
        f.merge_to("develop")
        f.assert_full_semver("1.4.0-alpha.2", c)
        f.make_a_commit("+semver: major")
        f.assert_full_semver("2.0.0-alpha.3", c)
        f.apply_tag("2.1.0-alpha.1")
        f.assert_full_semver("2.1.0-alpha.1", c)
        f.make_a_commit()
        f.assert_full_semver("2.1.0-alpha.2", c)
        f.checkout("main")
        if with_pr:
            f.branch_to("pull/2/merge")
            f.merge_no_ff("develop")
            f.assert_full_semver("2.1.0-PullRequest2.5", c)
            f.checkout("main")
            f.delete_branch("pull/2/merge")
        f.merge_no_ff("develop")
        f.assert_full_semver("2.1.0-5", c)
        f.make_a_commit()
        f.assert_full_semver("2.1.0-6", c)
        f.apply_tag("2.1.0")
        f.assert_full_semver("2.1.0", c)


