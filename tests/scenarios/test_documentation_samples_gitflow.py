def _finish_into(f: Scenario, target: str, branch: str, pr_version: str, with_pr: bool) -> None:
    """The shared "merge via optional pull request, then delete" tail of each sample."""
    f.checkout(target)
    if with_pr:
        f.branch_to("pull/2/merge")
        f.merge_no_ff(branch)
        f.assert_full_semver(pr_version, gitflow())
        f.checkout(target)
        f.delete_branch("pull/2/merge")
    f.merge_no_ff(branch)
    f.delete_branch(branch)


@pytest.mark.parametrize("with_pr", [False, True])
def test_feature_from_main_branch(with_pr: bool) -> None:
    c = gitflow()
    with Scenario() as f:
        f.make_a_commit()
        f.apply_tag("1.2.0")
        f.assert_full_semver("1.2.0", c)
        f.branch_to("feature/foo")
        f.assert_full_semver("1.2.1-foo.1+0", c)
        f.make_a_commit()
        f.assert_full_semver("1.2.1-foo.1+1", c)
        f.checkout("main")
        f.make_a_commit()
        f.assert_full_semver("1.2.1-1", c)
        f.apply_tag("1.2.1")
        f.assert_full_semver("1.2.1", c)
        f.merge_to("feature/foo")
        f.assert_full_semver("1.2.2-foo.1+2", c)
        f.make_a_commit("+semver: minor")
        f.assert_full_semver("1.3.0-foo.1+3", c)
        f.apply_tag("2.0.0-foo.1")
        f.assert_full_semver("2.0.0-foo.2+0", c)
        f.make_a_commit()
        f.assert_full_semver("2.0.0-foo.2+1", c)
        _finish_into(f, "main", "feature/foo", "2.0.0-PullRequest2.5", with_pr)
        f.assert_full_semver("2.0.0-5", c)
        f.make_a_commit()
        f.assert_full_semver("2.0.0-6", c)
        f.apply_tag("2.0.0")
        f.assert_full_semver("2.0.0", c)


